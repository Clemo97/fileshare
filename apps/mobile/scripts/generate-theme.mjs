// Generates src/theme/colors.ts from the web app's shadcn themes so both apps share
// one palette. Run from apps/mobile:  node scripts/generate-theme.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '../../../file-share-rtc/styles/colors.ts');
const target = path.resolve(here, '../src/theme/colors.ts');

// The web file is plain data plus one type import; strip the types and evaluate it.
const code = fs
  .readFileSync(source, 'utf8')
  .replace(/^import .*$/m, '')
  .replace(/\} satisfies Record<[^>]*>/, '}')
  .replace('export const themes =', 'const themes =');
const themes = new Function(`${code}\nreturn themes;`)();

const camel = (key) => key.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
// "262.1 83.3% 57.8%" -> "hsl(262.1, 83.3%, 57.8%)" (React Native wants the comma form)
const hsl = (value) => `hsl(${value.trim().split(/\s+/).join(', ')})`;

// Some themes carry extra non-colour tokens (e.g. `radius`); keep only the shared colour tokens.
const colorKeys = Object.keys(themes.default.light);
const keys = colorKeys.map(camel);
const body = Object.entries(themes)
  .map(([name, modes]) => {
    const mode = (colors) =>
      colorKeys
        .map((key) => `      ${camel(key)}: '${hsl(colors[key])}',`)
        .join('\n');
    return `  ${name}: {\n    light: {\n${mode(modes.light)}\n    },\n    dark: {\n${mode(modes.dark)}\n    },\n  },`;
  })
  .join('\n');

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(
  target,
  `// Generated by scripts/generate-theme.mjs from file-share-rtc/styles/colors.ts. Do not edit by hand.

export type ThemeColors = {
${keys.map((key) => `  ${key}: string;`).join('\n')}
};

export const themes = {
${body}
} as const satisfies Record<string, { light: ThemeColors; dark: ThemeColors }>;

export type ThemeName = keyof typeof themes;
`,
);

console.log(`wrote ${path.relative(process.cwd(), target)}: ${Object.keys(themes).length} themes, ${keys.length} tokens each`);
